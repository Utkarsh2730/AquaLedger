"use client";

import { Suspense, useEffect, useState } from "react";
import { useSearchParams } from "next/navigation";
import { client, inr, type BillModel } from "@/lib/client";
import type { Schema } from "@/amplify/data/resource";
import { useSociety } from "@/components/SocietyContext";
import BackLink from "@/components/BackLink";
import { Button, ErrorBox, Spinner } from "@/components/ui";
import { monthLabel } from "@/lib/core/time";

/**
 * Printable bill. "Download PDF" uses the browser's print-to-PDF, which costs nothing and
 * replaces generating PDFs in Lambda and storing them in S3.
 */
function BillView() {
  const { societyId } = useSociety();
  const id = useSearchParams().get("id") ?? "";
  const [bill, setBill] = useState<BillModel | null>(null);
  const [society, setSociety] = useState<Schema["Society"]["type"] | null>(null);
  const [error, setError] = useState<unknown>(null);

  useEffect(() => {
    Promise.all([client.models.Bill.get({ id }), client.models.Society.get({ societyId })])
      .then(([b, s]) => {
        if (!b.data) throw new Error("Bill not found");
        setBill(b.data);
        setSociety(s.data);
      })
      .catch(setError);
  }, [id, societyId]);

  if (error) return <ErrorBox error={error} />;
  if (!bill) return <Spinner />;
  const rows: [string, string][] = [
    ["Water used", `${Math.round(bill.litres ?? 0).toLocaleString("en-IN")} litres`],
    ["Your share of society usage", `${(bill.sharePct ?? 0).toFixed(3)}%`],
    ["Society water cost this month", inr(bill.totalWaterCost)],
    ["Usage charge (share × cost)", inr(bill.usageCharge)],
    ["Common-area charge", inr(bill.commonCharge)],
  ];
  return (
    <div className="mx-auto max-w-2xl">
      <div className="no-print mb-4 flex items-center justify-between gap-2">
        <BackLink fallback="/bills" fallbackLabel="All bills" />
        <Button onClick={() => window.print()}>Download PDF / Print</Button>
      </div>
      <article className="rounded-xl border border-slate-200 bg-white p-8 shadow-sm print:border-0 print:shadow-none">
        <header className="flex items-start justify-between border-b border-slate-200 pb-6">
          <div>
            <div className="text-lg font-semibold text-brand-700">💧 {society?.name ?? "Society"}</div>
            <div className="text-sm text-slate-500">{society?.city}</div>
          </div>
          <div className="text-right text-sm">
            <div className="font-semibold">Water bill · {monthLabel(bill.month)}</div>
            <div className="text-slate-500">Flat {bill.flatLabel}</div>
            <div className="text-slate-500">Status: {bill.status}</div>
          </div>
        </header>
        <table className="my-6 w-full text-sm">
          <tbody className="divide-y divide-slate-100">
            {rows.map(([k, v]) => (
              <tr key={k}>
                <td className="py-2 text-slate-600">{k}</td>
                <td className="py-2 text-right font-medium">{v}</td>
              </tr>
            ))}
          </tbody>
          <tfoot>
            <tr className="border-t-2 border-slate-900">
              <td className="pt-3 text-base font-semibold">Amount due</td>
              <td className="pt-3 text-right text-xl font-semibold">{inr(bill.amount)}</td>
            </tr>
          </tfoot>
        </table>
        <p className="text-xs text-slate-500">
          Billed by actual metered usage: the society’s total water cost (municipal supply, borewell electricity and tanker purchases) is divided in proportion to each flat’s
          metered litres. Generated by AquaLedger.
        </p>
      </article>
    </div>
  );
}

export default function BillViewPage() {
  return (
    <Suspense fallback={<Spinner />}>
      <BillView />
    </Suspense>
  );
}
